import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { DiagnosticTarget, EmitContext } from "@typespec/compiler";
import { emitFile, NoTarget, resolvePath } from "@typespec/compiler";
import { getDoc, getSummary } from "@typespec/compiler";
import { emitHttpZod, type EmittedService } from "typespec-http-zod";
import type { EmitterOptions } from "./lib.js";
import { PACKAGE_NAME, reportDiagnostic } from "./lib.js";
import { nameTools } from "./names.js";
import { collisionsFor } from "./coexistence.js";
import { refusalFor, warningsFor } from "./refusals.js";
import { renderTools, type ToolEntry } from "./tools.js";
import { selectTools } from "./select.js";

/**
 * Where emitted output imports its runtime from. Declared where the import is rendered, and
 * re-exported here beside the code that writes the file.
 */
export { DEFAULT_RUNTIME_MODULE } from "./tools.js";

/** Where this package's own runtime source lives, to be copied beside the generated code. */
const RUNTIME_SOURCE = fileURLToPath(new URL("../../src/runtime.ts", import.meta.url));

/** The header the emitted runtime carries, matching every other generated file. */
function generatedRuntimeBanner(hint: string | undefined): string {
	const second =
		hint === undefined
			? "// A copy of this package's runtime, emitted so the generated code imports no package at run time."
			: `// Regenerate with: ${hint}`;
	return `// GENERATED by typespec-http-mcp. DO NOT EDIT.
${second}
`;
}

/**
 * The options with `runtime-module` refused and removed, at the top level and per service.
 *
 * **Removed, not only reported**, because the library validates nothing about a key it no longer
 * declares, and a wrapper passing options through should not hand it one. The same refusal the
 * sibling server emitter makes, for the same option.
 */
function withoutRuntimeModule(context: EmitContext): EmitContext {
	const options = context.options as Record<string, unknown> & {
		services?: Record<string, Record<string, unknown>>;
	};
	const refuse = (value: unknown): void => {
		reportDiagnostic(context.program, {
			code: "runtime-module-removed",
			format: { value: String(value) },
			target: NoTarget,
		});
	};
	const { "runtime-module": topLevel, services, ...rest } = options;
	if (topLevel !== undefined) refuse(topLevel);
	const kept =
		services === undefined
			? undefined
			: Object.fromEntries(
					Object.entries(services).map(([name, service]) => {
						const { "runtime-module": perService, ...others } = service;
						if (perService !== undefined) refuse(perService);
						return [name, others];
					}),
				);
	return {
		...context,
		options: kept === undefined ? rest : { ...rest, services: kept },
	} as EmitContext;
}

/** The per-service view of the options, after the top-level defaults have been applied. */
interface ResolvedToolOptions {
	readonly emitTools: boolean;
	readonly toolTags: readonly string[] | undefined;
	readonly excludeTags: readonly string[];
	readonly toolPrefix: string | undefined;
}

function resolveToolOptions(options: EmitterOptions, serviceName: string): ResolvedToolOptions {
	const perService = options.services?.[serviceName];
	return {
		emitTools: perService?.["emit-tools"] ?? true,
		toolTags: perService?.["tool-tags"] ?? options["tool-tags"],
		excludeTags: perService?.["exclude-tags"] ?? options["exclude-tags"] ?? [],
		toolPrefix: perService?.["tool-prefix"] ?? options["tool-prefix"],
	};
}

/**
 * Where a diagnostic about an operation should point: the operation the library collected the route
 * from, by its id.
 *
 * **Never by name, and never by verb and path.** A name never matches an operation declared inside
 * an `interface`, whose id carries the interface; verb and path are shared by every member of a
 * `@sharedRoute`, so each member's diagnostic pointed at one of them.
 */
function targetFor(
	emitted: EmittedService,
	operationId: string,
): DiagnosticTarget | typeof NoTarget {
	return emitted.operations.get(operationId)?.operation ?? NoTarget;
}

/**
 * Run the library, then add the MCP surface beside what it wrote.
 *
 * **This file may import only `./lib.js`, its own modules, the library's public API and external
 * packages.** The same rule the library's own emitter entry point holds itself to, and for the same
 * reason: it makes "the published API is sufficient to build an emitter on" true by construction
 * rather than by assertion.
 */
export async function $onEmit(context: EmitContext): Promise<void> {
	const options = context.options as EmitterOptions;

	/**
	 * Raised once per program, before anything is written: it is about the arrangement, not about any
	 * one service, and a consumer needs to see it before they trust what landed on disk.
	 */
	for (const collision of collisionsFor(context.program, PACKAGE_NAME, context.emitterOutputDir)) {
		reportDiagnostic(context.program, {
			code: "shared-output-dir",
			target: NoTarget,
			format: { emitter: collision.emitter, differing: collision.differing.join(", ") },
		});
	}

	for (const emitted of await emitHttpZod(withoutRuntimeModule(context))) {
		await emitFile(context.program, {
			path: resolvePath(emitted.outputDir, "mcp-runtime.gen.ts"),
			content: `${generatedRuntimeBanner(emitted.options.regenerateHint)}${readFileSync(
				RUNTIME_SOURCE,
				"utf8",
			)}`,
		});

		const serviceName = emitted.service.namespace.name;
		const resolved = resolveToolOptions(options, serviceName);
		if (!resolved.emitTools) continue;

		const selection = selectTools(context.program, emitted.routes, emitted.operations, {
			toolTags: resolved.toolTags,
			excludeTags: resolved.excludeTags,
		});

		if (selection.selected.length === 0) {
			reportDiagnostic(context.program, {
				code: "no-tools-selected",
				target: NoTarget,
				format: {
					service: serviceName,
					configured:
						resolved.toolTags === undefined
							? "(unset, so every operation)"
							: resolved.toolTags.join(", "),
					available: selection.available.length === 0 ? "(none)" : selection.available.join(", "),
				},
			});
			continue;
		}

		const named = nameTools(selection.selected, resolved.toolPrefix);

		for (const refused of named.unrepresentable) {
			reportDiagnostic(context.program, {
				code: "unrepresentable-tool-name",
				target: targetFor(emitted, refused.operationId),
				format: { name: refused.name },
			});
		}
		for (const collision of named.collisions) {
			reportDiagnostic(context.program, {
				code: "tool-name-collision",
				target: targetFor(emitted, collision.second),
				format: { first: collision.first, second: collision.second, name: collision.name },
			});
		}

		const entries: ToolEntry[] = [];
		/**
		 * Refusals counted as they happen, so the invariant below can be arithmetic rather than a
		 * guess. A silent drop is then impossible: the numbers stop adding up.
		 */
		let refused = named.unrepresentable.length + named.collisions.length * 2;
		for (const route of emitted.routes) {
			const toolName = named.names.get(route.operationId);
			if (toolName === undefined) continue;
			const names = emitted.schemaNames.get(route.operationId);
			const operation = emitted.operations.get(route.operationId);
			if (names === undefined || operation === undefined) continue;

			/** A refusal removes the operation from the surface, so it is counted, never skipped. */
			const refusal = refusalFor(context.program, route, operation);
			if (refusal !== undefined) {
				refused += 1;
				reportDiagnostic(context.program, {
					code: refusal.kind,
					target: targetFor(emitted, route.operationId),
					format: { operationId: route.operationId, types: refusal.types },
				});
				continue;
			}

			const description = getDoc(context.program, operation.operation);
			const title = getSummary(context.program, operation.operation);
			const described = description !== undefined || title !== undefined;
			for (const warning of warningsFor(route, names, described)) {
				const target = targetFor(emitted, route.operationId);
				if (warning.code === "unvalidated-response-media-type") {
					reportDiagnostic(context.program, {
						code: warning.code,
						target,
						format: { operationId: route.operationId, ...warning.format },
					});
				} else {
					reportDiagnostic(context.program, {
						code: warning.code,
						target,
						format: { operationId: route.operationId },
					});
				}
			}

			entries.push({
				route,
				names,
				toolName,
				/**
				 * **Read from the IR, not re-derived.** The library publishes the document's own
				 * requirements as of 0.25.0; before that it published only a flat scope union and a
				 * boolean, so both server emitters rebuilt this by hand from a third read of the
				 * program. Two hand-written copies of one rule, neither compared against the other.
				 */
				requirements: route.security,
				/**
				 * **The description a model reads to decide whether to call this tool.**
				 *
				 * `@doc` rather than `@summary`: the summary becomes the tool's `title`, which is for
				 * display. Both are published by `@typespec/openapi3`, so neither is a new fact.
				 */
				description,
				/**
				 * **Read from `@summary` directly, not from `EmittedRoute.summary`.**
				 *
				 * The library's `summary` is `getSummary ?? getDoc`, which is right for its purposes and
				 * wrong here: with only a doc comment declared it would emit a `title` byte-identical to
				 * the `description`, so every tool would carry the same sentence twice in a payload the
				 * model reads. A title is for display and is absent unless the spec declares one.
				 */
				title,
			});
		}

		/**
		 * **`emitted + refused === selected`, asserted from structured counts rather than by reading
		 * the file back.** Deciding anything by pattern-matching emitted text is how this estate
		 * acquired a class of defect it then had to hunt for.
		 */
		if (entries.length + refused !== selection.selected.length) {
			throw new Error(
				`typespec-http-mcp internal invariant: ${entries.length} emitted + ${refused} refused ` +
					`!== ${selection.selected.length} selected for '${serviceName}'`,
			);
		}

		const rendered = renderTools(
			entries,
			emitted.routes.map((route) => route.operationId),
			{
				sealed: emitted.options.sealObjectSchemas,
				hint: emitted.options.regenerateHint,
			},
		);
		await emitFile(context.program, {
			path: resolvePath(emitted.outputDir, "mcp.gen.ts"),
			content: rendered.text,
		});
	}
}
