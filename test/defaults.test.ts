import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { compileFixture } from "./support/compile-fixture.js";

/**
 * **The branch every other suite configures away.**
 *
 * Each fixture here sets `runtime-module`, so without this suite nothing would ever compile the
 * emitter's own default. In the sibling package a defect lived in exactly that gap for the whole
 * life of the package: `tsp compile` succeeded with zero diagnostics and `tsc` then reported
 * `Cannot find module` in every generated file, because the shipped default pointed somewhere that
 * did not resolve from consumer code.
 *
 * So this compiles with NOTHING configured but the output directory -- the configuration the
 * README's own example produces.
 */

const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const reference = join(packageRoot, "test", "reference");

describe("the default runtime-module, which nothing else exercises", () => {
	it("emits the runtime beside the generated code, and the generated code points at it", async () => {
		const { outDir, diagnostics } = await compileFixture(reference, "service", {
			bare: true,
			outName: "defaults-bare",
		});
		expect(diagnostics.filter((d) => d.severity === "error")).toEqual([]);

		const runtime = join(outDir, "mcp-runtime.gen.ts");
		expect(existsSync(runtime)).toBe(true);

		// The specifier the library wrote into its own output must name the file this emitter wrote.
		const schemas = readFileSync(join(outDir, "schemas.gen.ts"), "utf8");
		expect(schemas).toContain('from "./mcp-runtime.gen.js"');
	}, 300_000);

	/**
	 * **Nothing the emitter writes may import a build-time package.**
	 *
	 * A consumer installs this emitter as a devDependency. An emitted import of it, or of the library
	 * it runs, is a deployment that fails at run time and nowhere earlier -- which is why the runtime
	 * is COPIED into the output rather than imported from here.
	 */
	it("emits a runtime that imports only declared peers", async () => {
		const { outDir } = await compileFixture(reference, "service", {
			bare: true,
			outName: "defaults-imports",
		});
		const runtime = readFileSync(join(outDir, "mcp-runtime.gen.ts"), "utf8");
		const specifiers = [...runtime.matchAll(/from "([^"]+)"/g)].map((m) => m[1] ?? "");
		expect(specifiers.length).toBeGreaterThanOrEqual(2);
		expect(specifiers.toSorted()).toEqual(["@modelcontextprotocol/server", "zod"]);
	}, 300_000);

	it("carries the generated banner, so nobody edits it by mistake", async () => {
		const { outDir } = await compileFixture(reference, "service", {
			bare: true,
			outName: "defaults-banner",
		});
		const runtime = readFileSync(join(outDir, "mcp-runtime.gen.ts"), "utf8");
		expect(runtime.startsWith("// GENERATED by typespec-http-mcp. DO NOT EDIT.")).toBe(true);
		expect(runtime).toContain("Point `runtime-module` at a module of your own");
	}, 300_000);

	/**
	 * The other half of the branch, and the one that makes the arm above mean something: an
	 * application that supplied its own runtime must not find a file it did not ask for in its output.
	 */
	it("emits NO runtime when the application supplied one", async () => {
		const { outDir } = await compileFixture(reference, "service", {
			outName: "defaults-substituted",
		});
		expect(existsSync(join(outDir, "mcp-runtime.gen.ts"))).toBe(false);
		// And the generated code points at what was supplied instead.
		const schemas = readFileSync(join(outDir, "schemas.gen.ts"), "utf8");
		expect(schemas).not.toContain('from "./mcp-runtime.gen.js"');
	}, 300_000);
});
